    #[must_use]
    pub fn css_custom_properties(&self) -> String {
        let mode = match self.mode {
            ThemeMode::Light => "light",
            ThemeMode::Dark => "dark",
            ThemeMode::HighContrast => "high-contrast",
        };
        format!(
            concat!(
                "--dtc-theme-mode: '{}';",
                "--dtc-surface: {};",
                "--dtc-surface-panel: {};",
                "--dtc-surface-subtle: {};",
                "--dtc-surface-muted: {};",
                "--dtc-surface-input: {};",
                "--dtc-text: {};",
                "--dtc-text-muted: {};",
                "--dtc-text-subtle: {};",
                "--dtc-text-inverse: {};",
                "--dtc-border: {};",
                "--dtc-border-muted: {};",
                "--dtc-border-strong: {};",
                "--dtc-accent: {};",
                "--dtc-accent-hover: {};",
                "--dtc-accent-surface: {};",
                "--dtc-accent-surface-muted: {};",
                "--dtc-accent-border: {};",
                "--dtc-accent-text: {};",
                "--dtc-focus: {};",
                "--dtc-success: {};",
                "--dtc-success-surface: {};",
                "--dtc-success-border: {};",
                "--dtc-success-text: {};",
                "--dtc-warning: {};",
                "--dtc-warning-surface: {};",
                "--dtc-warning-border: {};",
                "--dtc-warning-text: {};",
                "--dtc-danger: {};",
                "--dtc-danger-surface: {};",
                "--dtc-danger-border: {};",
                "--dtc-danger-text: {};",
                "--dtc-info-surface: {};",
                "--dtc-info-border: {};",
                "--dtc-info-text: {};",
                "--dtc-kbd-surface: {};",
                "--dtc-kbd-border: {};",
                "--dtc-kbd-border-strong: {};",
                "--dtc-kbd-text: {};",
                "--dtc-shadow-soft: {};",
                "--dtc-shadow-medium: {};",
                "--dtc-shadow-inset: {};",
            ),
            mode,
            self.surface,
            self.surface_panel,
            self.surface_subtle,
            self.surface_muted,
            self.surface_input,
            self.text,
            self.text_muted,
            self.text_subtle,
            self.text_inverse,
            self.border,
            self.border_muted,
            self.border_strong,
            self.accent,
            self.accent_hover,
            self.accent_surface,
            self.accent_surface_muted,
            self.accent_border,
            self.accent_text,
            self.focus,
            self.success,
            self.success_surface,
            self.success_border,
            self.success_text,
            self.warning,
            self.warning_surface,
            self.warning_border,
            self.warning_text,
            self.danger,
            self.danger_surface,
            self.danger_border,
            self.danger_text,
            self.info_surface,
            self.info_border,
            self.info_text,
            self.kbd_surface,
            self.kbd_border,
            self.kbd_border_strong,
            self.kbd_text,
            self.shadow_soft,
            self.shadow_medium,
            self.shadow_inset,
        )
    }

    #[must_use]
    pub fn css_rule(&self, selector: &str) -> String {
        format!("{} {{{}}}", selector, self.css_custom_properties())
    }
