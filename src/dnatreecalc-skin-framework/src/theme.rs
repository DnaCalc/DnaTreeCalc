use serde::{Deserialize, Serialize};

/// Presentation theme selected by the host shell.
///
/// This is frame/chrome presentation only. Value formatting, conditional
/// formatting, and rendered value text remain engine-owned.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum ThemeMode {
    #[default]
    Light,
    Dark,
    HighContrast,
}

/// Skin-visible design tokens.
///
/// Skins should consume these through CSS custom properties (`var(--dtc-...)`)
/// and through this typed context when they need to branch on the active mode.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
